-- 9. RPC: get_user_ai_chat_quota (Query quota status for user or dev admin)
create or replace function public.get_user_ai_chat_quota(p_user_id uuid default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_target_user uuid := coalesce(p_user_id, auth.uid());
  v_day date := (now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_override public.ai_chat_user_quota%rowtype;
  v_used integer := 0;
  v_daily_limit integer := 10;
  v_is_unlimited boolean := false;
  v_has_override boolean := false;
  v_caller_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_is_admin boolean := (v_caller_email = 'vinhlt@ghn.vn' or coalesce(auth.jwt() ->> 'role', '') = 'service_role');
begin
  if v_target_user is null then
    raise exception 'AI_CHAT_USER_REQUIRED' using errcode = '42501';
  end if;
  if v_target_user <> auth.uid() and not v_is_admin then
    raise exception 'AI_CHAT_FORBIDDEN' using errcode = '42501';
  end if;

  -- Check override
  select * into v_override from public.ai_chat_user_quota where user_id = v_target_user;
  if found then
    v_has_override := true;
    if v_override.is_unlimited then
      v_is_unlimited := true;
      v_daily_limit := null;
    else
      v_daily_limit := v_override.daily_turn_limit;
    end if;
  end if;

  -- Check usage today
  select turn_count into v_used from public.ai_chat_quota_daily
  where scope_type = 'user' and scope_id = v_target_user::text and usage_date = v_day;
  v_used := coalesce(v_used, 0);

  return jsonb_build_object(
    'userId', v_target_user,
    'quotaDate', v_day,
    'dailyLimit', v_daily_limit,
    'usedToday', v_used,
    'isUnlimited', v_is_unlimited,
    'hasOverride', v_has_override,
    'remainingTurns', case when v_is_unlimited then null else greatest(0, v_daily_limit - v_used) end,
    'resetAt', ((v_day + 1)::timestamp at time zone 'Asia/Ho_Chi_Minh')
  );
end;
$$;

-- 10. RPC: admin_set_user_quota_override
create or replace function public.admin_set_user_quota_override(
  p_user_id uuid,
  p_user_email text,
  p_daily_turn_limit integer,
  p_is_unlimited boolean,
  p_reason text,
  p_changed_by text default null
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_caller_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_changed_by text := coalesce(nullif(lower(trim(p_changed_by)), ''), nullif(v_caller_email, ''), 'service_role');
  v_is_admin boolean := (v_caller_email = 'vinhlt@ghn.vn' or coalesce(auth.jwt() ->> 'role', '') = 'service_role');
  v_old public.ai_chat_user_quota%rowtype;
begin
  if not v_is_admin then
    raise exception 'AI_CHAT_ADMIN_REQUIRED' using errcode = '42501';
  end if;
  if p_reason is null or trim(p_reason) = '' then
    raise exception 'AI_CHAT_REASON_REQUIRED' using errcode = '22023';
  end if;
  if not p_is_unlimited and (p_daily_turn_limit is null or p_daily_turn_limit < 0) then
    raise exception 'AI_CHAT_INVALID_LIMIT' using errcode = '22023';
  end if;

  select * into v_old from public.ai_chat_user_quota where user_id = p_user_id;

  insert into public.ai_chat_user_quota (
    user_id, user_email, daily_turn_limit, is_unlimited, updated_by, reason, updated_at
  ) values (
    p_user_id, lower(p_user_email), case when p_is_unlimited then null else p_daily_turn_limit end,
    p_is_unlimited, v_changed_by, trim(p_reason), now()
  ) on conflict (user_id) do update set
    daily_turn_limit = excluded.daily_turn_limit,
    is_unlimited = excluded.is_unlimited,
    updated_by = excluded.updated_by,
    reason = excluded.reason,
    updated_at = now();

  insert into public.ai_chat_quota_audit (
    user_id, user_email, previous_limit, previous_is_unlimited,
    new_limit, new_is_unlimited, action, changed_by, reason
  ) values (
    p_user_id, lower(p_user_email), v_old.daily_turn_limit, coalesce(v_old.is_unlimited, false),
    case when p_is_unlimited then null else p_daily_turn_limit end, p_is_unlimited,
    'set_override', v_changed_by, trim(p_reason)
  );

  return jsonb_build_object('success', true, 'userId', p_user_id, 'isUnlimited', p_is_unlimited, 'limit', p_daily_turn_limit);
end;
$$;

-- 11. RPC: admin_reset_user_quota
create or replace function public.admin_reset_user_quota(
  p_user_id uuid,
  p_reason text,
  p_changed_by text default null
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_caller_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_changed_by text := coalesce(nullif(lower(trim(p_changed_by)), ''), nullif(v_caller_email, ''), 'service_role');
  v_is_admin boolean := (v_caller_email = 'vinhlt@ghn.vn' or coalesce(auth.jwt() ->> 'role', '') = 'service_role');
  v_old public.ai_chat_user_quota%rowtype;
begin
  if not v_is_admin then
    raise exception 'AI_CHAT_ADMIN_REQUIRED' using errcode = '42501';
  end if;
  if p_reason is null or trim(p_reason) = '' then
    raise exception 'AI_CHAT_REASON_REQUIRED' using errcode = '22023';
  end if;

  select * into v_old from public.ai_chat_user_quota where user_id = p_user_id;
  if not found then
    return jsonb_build_object('success', true, 'message', 'User already on default quota');
  end if;

  delete from public.ai_chat_user_quota where user_id = p_user_id;

  insert into public.ai_chat_quota_audit (
    user_id, user_email, previous_limit, previous_is_unlimited,
    new_limit, new_is_unlimited, action, changed_by, reason
  ) values (
    p_user_id, v_old.user_email, v_old.daily_turn_limit, v_old.is_unlimited,
    10, false, 'reset_default', v_changed_by, trim(p_reason)
  );

  return jsonb_build_object('success', true, 'userId', p_user_id, 'defaultLimit', 10);
end;
$$;

-- 12. RPC: purge_old_ai_chat_questions (Retention Policy - default 90 days)
create or replace function public.purge_old_ai_chat_questions(
  p_retention_days integer default 90
) returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_caller_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_is_admin boolean := (v_caller_email = 'vinhlt@ghn.vn' or coalesce(auth.jwt() ->> 'role', '') = 'service_role');
  v_cutoff timestamptz;
  v_purged integer := 0;
begin
  if not v_is_admin then
    raise exception 'AI_CHAT_ADMIN_REQUIRED' using errcode = '42501';
  end if;
  if p_retention_days < 1 then
    raise exception 'AI_CHAT_INVALID_RETENTION' using errcode = '22023';
  end if;

  v_cutoff := now() - (p_retention_days || ' days')::interval;

  update public.ai_chat_requests
  set question = '[PURGED_BY_RETENTION]',
      question_normalized = '[PURGED]'
  where started_at < v_cutoff
    and question is not null
    and question <> '[PURGED_BY_RETENTION]';

  get diagnostics v_purged = row_count;
  return v_purged;
