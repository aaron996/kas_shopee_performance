-- Migration: AI Operations, Quota Overrides, and Question Research Layer
-- Applies quota overrides, audit logging, research telemetry, retention purging, and dev-admin RPCs.

-- 1. Table: User Quota Overrides
create table if not exists public.ai_chat_user_quota (
  user_id uuid primary key,
  user_email text not null,
  daily_turn_limit integer check (daily_turn_limit is null or daily_turn_limit >= 0),
  is_unlimited boolean not null default false,
  updated_by text not null,
  reason text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ai_chat_user_quota_limit_check check (
    (is_unlimited = true and daily_turn_limit is null) or
    (is_unlimited = false and daily_turn_limit is not null)
  )
);

-- 2. Table: Quota Audit Log
create table if not exists public.ai_chat_quota_audit (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  user_email text,
  previous_limit integer,
  previous_is_unlimited boolean default false,
  new_limit integer,
  new_is_unlimited boolean default false,
  action text not null check (action in ('set_override', 'reset_default')),
  changed_by text not null,
  reason text not null,
  created_at timestamptz not null default now()
);

